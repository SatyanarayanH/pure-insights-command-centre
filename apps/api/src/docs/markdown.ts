import {
  CLIENT_MESSAGE_DEFINITIONS,
  PERMISSIONS,
  ROLE_DEFINITIONS,
  ROLES,
  SERVER_EVENT_DEFINITIONS,
  SERVER_EVENT_TYPES,
  WS_CLOSE_CODES,
} from '@picc/contracts';
import { DEFAULT_ALERT_RULES } from '../alerts/rules.js';
import { API_PREFIX } from '../config.js';
import type { RouteDefinition } from '../http/registry.js';
import { periodLabel, type WarehouseSnapshot } from '../warehouse/snapshot.js';

const table = (header: string[], rows: (string | number)[][]): string =>
  [
    `| ${header.join(' | ')} |`,
    `| ${header.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ].join('\n');

const GENERATED =
  '<!-- Generated by `npm run docs:generate`. Do not edit by hand: change the code and regenerate. -->';
const num = (n: number | null, digits = 0): string =>
  n === null
    ? '—'
    : n.toLocaleString('en-US', { minimumFractionDigits: digits, maximumFractionDigits: digits });
const usd = (n: number | null): string => (n === null ? '—' : `$${num(n)}`);

/** Reference appendix of the technical specification: endpoints, access matrix, events. */
export function buildApiReference(routes: readonly RouteDefinition[]): string {
  const tags = [...new Set(routes.map((r) => r.tag))];
  const endpointSections = tags.map((tag) => {
    const rows = routes
      .filter((r) => r.tag === tag)
      .map((r) => [
        `\`${r.method.toUpperCase()}\``,
        `\`${API_PREFIX}${r.path}\``,
        r.summary,
        r.auth === 'public'
          ? 'public'
          : r.permission
            ? `\`${r.permission}\``
            : 'any signed-in user',
        r.rowScoped ? 'yes' : '',
      ]);
    return `### ${tag}\n\n${table(['Method', 'Path', 'Purpose', 'Permission', 'Row-scoped'], rows)}`;
  });

  const matrix = table(
    ['Permission', ...ROLES.map((r) => ROLE_DEFINITIONS[r].label)],
    PERMISSIONS.map((p) => [
      `\`${p}\``,
      ...ROLES.map((r) => (ROLE_DEFINITIONS[r].permissions.includes(p) ? '✓' : '')),
    ]),
  );
  const roles = table(
    ['Role', 'Data scope', 'Description'],
    ROLES.map((r) => [
      ROLE_DEFINITIONS[r].label,
      ROLE_DEFINITIONS[r].scope === 'own' ? 'own reports only' : 'all reports',
      ROLE_DEFINITIONS[r].description,
    ]),
  );
  const access = table(
    ['Endpoint', ...ROLES.map((r) => ROLE_DEFINITIONS[r].label)],
    routes
      .filter((r) => r.auth !== 'public')
      .map((r) => [
        `\`${r.method.toUpperCase()} ${r.path}\``,
        ...ROLES.map((role) => {
          const allowed =
            !r.permission || ROLE_DEFINITIONS[role].permissions.includes(r.permission);
          if (!allowed) return '403';
          return r.rowScoped && ROLE_DEFINITIONS[role].scope === 'own' ? 'own' : '✓';
        }),
      ]),
  );

  const events = table(
    ['Event `type`', 'Topic', 'When it is sent'],
    SERVER_EVENT_TYPES.map((type) => {
      const d = SERVER_EVENT_DEFINITIONS[type];
      return [`\`${type}\``, d.topic ? `\`${d.topic}\`` : '—', d.description];
    }),
  );
  const clientMessages = table(
    ['Message `type`', 'Purpose'],
    Object.entries(CLIENT_MESSAGE_DEFINITIONS).map(([type, d]) => [`\`${type}\``, d.description]),
  );
  const closeCodes = table(
    ['Code', 'Meaning'],
    Object.values(WS_CLOSE_CODES).map((c) => [String(c.code), c.reason]),
  );
  const rules = table(
    ['Rule', 'In brief', 'Fires when', 'Severity', 'Resolves after'],
    DEFAULT_ALERT_RULES.map((r) => [
      `\`${r.id}\``,
      r.inBrief ? 'yes' : 'no',
      r.id === 'latency'
        ? `load time > ${r.warningThreshold} s`
        : r.id === 'refresh_failure'
          ? 'refresh is FAILED or TIMED_OUT'
          : r.id === 'refresh_unknown'
            ? 'refresh is UNKNOWN'
            : 'credits < 0',
      r.id === 'latency'
        ? `warning > ${r.warningThreshold} s, high > ${r.highThreshold} s, critical > ${r.criticalThreshold} s`
        : r.id === 'refresh_failure'
          ? `high; critical from ${r.escalateAfter} consecutive failures`
          : r.id === 'refresh_unknown'
            ? 'info'
            : 'warning',
      `${r.resolveAfter} healthy observation${r.resolveAfter > 1 ? 's' : ''}`,
    ]),
  );

  return [
    '# API reference',
    '',
    GENERATED,
    '',
    `Generated from the route registry (\`apps/api/src/http/routes.ts\`) and the contracts package (\`packages/contracts\`). ${routes.length} REST operations, ${SERVER_EVENT_TYPES.length} server events.`,
    '',
    'Machine-readable versions: [`openapi.json`](api/openapi.json) (OpenAPI 3.1) and [`asyncapi.json`](api/asyncapi.json) (AsyncAPI 3.0). The running server also serves them at `/openapi.json`, `/asyncapi.json` and an interactive explorer at `/docs`.',
    '',
    '## REST endpoints',
    '',
    ...endpointSections.flatMap((s) => [s, '']),
    '## Roles',
    '',
    roles,
    '',
    '## Permission matrix',
    '',
    matrix,
    '',
    '## Access matrix',
    '',
    "`✓` allowed · `own` allowed, filtered to the caller's own reports · `403` refused. This table is derived from the same data the server enforces and the test suite checks (`apps/api/test/rbac.test.ts`).",
    '',
    access,
    '',
    '## Real-time events (server to client)',
    '',
    'Envelope: `{ "v": 1, "id": <integer>, "type": "<event type>", "ts": "<ISO-8601>", "data": { ... } }`',
    '',
    events,
    '',
    '## Client messages (WebSocket only)',
    '',
    clientMessages,
    '',
    '## WebSocket close codes',
    '',
    closeCodes,
    '',
    '## Alert rules (defaults)',
    '',
    rules,
    '',
  ].join('\n');
}

/** The data-quality report, written from the rule run itself. */
export function buildDataQualityReport(s: WarehouseSnapshot): string {
  const inBrief = s.dqRules.filter((r) => r.in_brief);
  const found = s.dqRules.filter((r) => !r.in_brief);
  const ruleRows = (rules: typeof s.dqRules) =>
    table(
      ['Rule', 'Name', 'Action', 'Rows', '% of rows', 'Reports', 'What it means'],
      rules.map((r) => [
        r.rule_id,
        `\`${r.rule_name}\``,
        r.action,
        num(r.rows_affected),
        `${r.pct_of_rows}%`,
        r.reports_affected,
        r.description,
      ]),
    );
  const quarantined = s.facts.filter((f) => f.is_cost_quarantined);
  const imputedCredits = quarantined.reduce((a, f) => a + (f.credits_fully_loaded ?? 0), 0);
  const imputedUsd = quarantined.reduce((a, f) => a + (f.snowflake_cost_loaded_usd ?? 0), 0);
  const reported = quarantined.reduce((a, f) => a + (f.credits_reported ?? 0), 0);
  const latestSeq = s.dim[0]?.latest_period_seq ?? 0;
  const orphansNow = s.dim.filter((d) => d.is_orphaned).length;
  const everOrphaned = s.dim.filter((d) => d.periods_orphaned > 0).length;
  const owners = s.dim.map((d) => d.distinct_owners);

  return [
    '# Data quality report',
    '',
    GENERATED,
    '',
    `Source: \`data/raw/Case_Study_3_Pure_Insights_Monitoring.csv\` · ${num(s.facts.length)} rows · ${s.dim.length} reports · ${s.periodSummary.length} periods · engine: ${s.dialect}`,
    '',
    'Every number below is read from the tables the SQL suite produced (`DQ.RULE_SUMMARY`, `DQ.QUARANTINE`, `DQ.RECONCILIATION`). Nothing is typed in by hand, so the report cannot disagree with the pipeline.',
    '',
    '## Shape of the dataset',
    '',
    `The file has ${num(s.facts.length)} rows but only ${s.dim.length} distinct \`report_id\` values. Each report appears exactly ${s.periodSummary.length} times, in repeating blocks of ${s.dim.length} rows, and there is no date column. The rows are therefore treated as **${s.periodSummary.length} consecutive reporting periods of the same ${s.dim.length} reports** (a panel), keyed \`(report_id, period_seq)\`. De-duplicating on \`report_id\` would discard ${num(s.facts.length - s.dim.length)} observations; treating each row as its own report would count every report ${s.periodSummary.length} times.`,
    '',
    `Periods are labelled ${periodLabel(0)} to ${periodLabel(latestSeq)}. "Current state" means ${periodLabel(latestSeq)}.`,
    '',
    '## Defects listed in the brief',
    '',
    ruleRows(inBrief),
    '',
    '## Defects found by profiling',
    '',
    'Not mentioned in the brief. Each one would have produced a wrong number or a runtime error if left alone.',
    '',
    ruleRows(found),
    '',
    '## How each defect is handled',
    '',
    `- **Orphaned owners.** \`nan\` (a pandas NaN that was stringified on export) and \`ORPHANED_REPORT\` (the portal's sentinel) are two spellings of the same thing. Both become a NULL owner with \`is_orphaned = TRUE\`; the original encoding is kept in \`orphan_encoding\`. ${orphansNow} reports are orphaned in ${periodLabel(latestSeq)}; ${everOrphaned} of ${s.dim.length} were orphaned in at least one period.`,
    `- **Negative credits.** ${quarantined.length} report-periods, ${num(reported, 2)} credits in total. Snowflake never meters negative compute, so the figure is a defect in the export, not a refund. The rows stay in staging; only the credit value is withheld from attribution and written to \`DQ.QUARANTINE\`. It is not deleted, not \`ABS()\`-ed and not set to zero. Because the queries behind those rows still ran, their cost is estimated independently from execution time (attribution Method C): **${num(imputedCredits)} credits, about ${usd(imputedUsd)}**. Filtering alone would have hidden that spend.`,
    `- **Latency.** ${num(s.dqRules.find((r) => r.rule_id === 'DQ-03')?.rows_affected ?? 0)} of ${num(s.facts.length)} observations exceed 15 seconds. That is a signal, not a defect, and it drives the alert engine. Because three quarters of observations breach, the engine tiers severity (15 / 30 / 45 s) and folds repeat breaches into one alert per report.`,
    `- **Usage versus AWS cost.** Hosting cost does not follow usage at all: the correlation between monthly views and AWS cost is ${s.correlations.find((c) => c.usage_measure === 'monthly_active_views' && c.cost_measure === 'aws_hosting_cost_usd')?.pearson_r?.toFixed(3)}. Row-level outliers are flagged with a modified z-score on log cost-per-view; report-level "zombies" (low usage, high cost) are listed in \`MART.COST_ANOMALIES\`.`,
    `- **Unknown refresh status.** Treated as a monitoring gap. It neither opens nor closes a refresh-failure alert.`,
    `- **Ownership churn.** Each report had between ${Math.min(...owners)} and ${Math.max(...owners)} different named owners across ${s.periodSummary.length} periods, so one snapshot cannot be trusted. The orphan queue therefore suggests the last known owner from history.`,
    `- **Zero views.** Unit cost per view is NULL for those rows (every division goes through \`NULLIF\`), never an error or infinity.`,
    '',
    '## Quarantine',
    '',
    table(
      ['Source line', 'Report', 'Period', 'Reported credits', 'Imputed credits', 'Imputed cost'],
      quarantined.map((f) => [
        f.row_seq + 1,
        f.report_id,
        periodLabel(f.period_seq),
        num(f.credits_reported, 2),
        num(f.credits_fully_loaded, 1),
        usd(f.snowflake_cost_loaded_usd),
      ]),
    ),
    '',
    '"Source line" is the line number in the CSV file (header is line 1).',
    '',
    '## Reconciliation',
    '',
    `${s.reconciliation.filter((r) => r.status === 'PASS').length} of ${s.reconciliation.length} checks pass. The suite refuses to hand data to the application if any check fails.`,
    '',
    table(
      ['Check', 'What is verified', 'Expected', 'Actual', 'Status'],
      s.reconciliation.map((r) => [
        r.check_id,
        r.description,
        num(r.expected_value, 2),
        num(r.actual_value, 2),
        r.status,
      ]),
    ),
    '',
  ].join('\n');
}
